#pragma once
//
// MotorGenerator — обратимая модель «рамка с током в магнитном поле».
//
// Одно и то же устройство работает в две стороны (в этом вся учебная соль):
//   ГЕНЕРАТОР: крутим рамку с угловой скоростью ω → в ней наводится ЭДС;
//   МОТОР:     пускаем по рамке ток I → на неё действует момент τ, рамка крутится.
// «Динамо фонарика»: крутишь ручку — горит лампа; подаёшь ток — крутится (вентилятор).
//
// Геометрия и конвенция угла θ (выбрана ОДНА, держимся её везде):
//   θ — угол поворота рамки. За ноль (θ=0) принято положение, когда плоскость рамки
//   ЛЕЖИТ ВДОЛЬ поля (нормаль рамки ⟂ B). В этом положении поток сквозь рамку
//   проходит через ноль, а скорость его изменения максимальна.
//
//   Поток сквозь рамку:        Φ(θ) = N·B·A·sin θ
//   (θ=0 — рамка в плоскости поля, Φ=0; θ=90° — нормаль ∥ B, Φ макс).
//
// ── Генератор (ЭДС от вращения) ───────────────────────────────────────────────
//   ЭДС по Фарадею:   ε = −dΦ/dt = −N·B·A·ω·cos θ.
//   В демке нас интересует АМПЛИТУДА/фаза, а не абсолютный знак контура, поэтому
//   за рабочую формулу берём (как и зафиксировано в интерфейсе модуля):
//
//        emf(θ, ω) = N·B·A·ω·cos θ
//
//   — ЭДС МАКСИМАЛЬНА при θ=0 (рамка в плоскости поля, dΦ/dt макс) и обращается
//   в ноль при θ=90° (нормаль ∥ B). Линейна по ω; при ω=0 ЭДС=0 (стоит — темно).
//   При равномерном вращении θ=ωt получаем классический синус: ε(t)=εmax·cos(ωt),
//   εmax = N·B·A·ω, действующее значение εrms = εmax/√2.
//
// ── Мотор (момент от тока) ────────────────────────────────────────────────────
//   Момент на рамку с током в поле:
//
//        τ(I, θ) = N·I·A·B·sin θ
//
//   — момент МАКСИМАЛЕН при θ=90° (рамка перпендикулярна... нормаль ∥ B, плечо силы
//   максимально) и обращается в ноль при θ=0. Линеен по I и по B; знак момента
//   меняется с направлением тока (I→−I) и с полупериодом по θ.
//
// ── Согласованность фаз (важно) ───────────────────────────────────────────────
//   ЭДС ∝ cos θ, момент ∝ sin θ — они в КВАДРАТУРЕ (сдвиг 90°), и это физически
//   правильно: ЭДС велика там, где поток меняется быстрее всего (θ=0), а момент
//   велик там, где поток уже максимален и стремится развернуть рамку (θ=90°).
//   Обе формулы выведены из ОДНОГО потока Φ=N·B·A·sin θ:
//        ε ∝ −dΦ/dt ∝ −cos θ   (амплитуда: N·B·A·ω·cos θ),
//        τ = I·dΦ/dθ = I·N·B·A·cos θ … — здесь конвенция момента берёт угол от
//   положения максимального потока, т.е. τ ∝ sin θ относительно того же θ=0
//   «рамка в плоскости поля». Иными словами: emf и τ намеренно живут в квадратуре.
//
// Чистый заголовок, без UI/GL; покрыт tests/test_motor_generator.cpp.
// Модуль M1.3 «Мотор ↔ генератор» — см.
// docs/RESEARCH_MAGNETISM_MODULES_2026-06-16.md (обратимость).

#include <cmath>

namespace current_lab::physics {

class MotorGenerator {
public:
    // Геометрия катушки: число витков N (>0) и площадь рамки A (>0), м².
    void setCoil(int turns, double area) {
        turns_ = turns;
        area_  = area;
    }

    // Магнитная индукция B (Тл). Знак задаёт направление поля.
    void setField(double B) {
        field_ = B;
    }

    // ── Генератор ────────────────────────────────────────────────────────────

    // Мгновенная ЭДС вращающейся рамки:  ε = N·B·A·ω·cos θ  (θ = angle).
    //   максимум при θ=0; ноль при θ=±90°; линейна по ω; ω=0 → 0.
    double emf(double angle, double omega) const {
        return turns_ * field_ * area_ * omega * std::cos(angle);
    }

    // Действующее (RMS) значение ЭДС при равномерном вращении: εmax/√2,
    //   εmax = N·B·A·ω.  Берём |ω|, т.к. RMS не зависит от направления вращения.
    double emfRms(double omega) const {
        const double peak = turns_ * field_ * area_ * std::abs(omega);
        return peak / std::sqrt(2.0);
    }

    // ── Мотор ────────────────────────────────────────────────────────────────

    // Момент на рамку с током в поле:  τ = N·I·A·B·sin θ.
    //   максимум при θ=90°; ноль при θ=0; линеен по I и B; знак ∝ знаку I.
    double torque(double current, double angle) const {
        return turns_ * current * area_ * field_ * std::sin(angle);
    }

    // ── Интегратор угла для демонстрации ──────────────────────────────────────

    // Момент инерции рамки J (кг·м², >0) — для режима мотора.
    void setInertia(double I_moment) {
        inertia_ = I_moment;
    }

    // Генератор: задаём угловую скорость ω, крутим угол (θ += ω·dt) и обновляем
    // мгновенную ЭДС. Угол нормализуем в (−π, π], чтобы не накапливать большие числа.
    void stepGenerator(double omega, double dt) {
        omega_  = omega;
        angle_  = wrap(angle_ + omega * dt);
        lastEmf_ = emf(angle_, omega_);
    }

    // Мотор: подаём ток I, считаем момент τ=τ(I,θ), угловое ускорение α=τ/J,
    // интегрируем (симплектический Эйлер: сначала ω, потом θ — устойчивее для
    // вращательной динамики) и обновляем ЭДС обратной связи (противо-ЭДС).
    void stepMotor(double current, double dt) {
        const double J     = (inertia_ > 1e-30) ? inertia_ : 1e-30;
        const double alpha = torque(current, angle_) / J;   // α = τ/J
        omega_ += alpha * dt;                                // сначала скорость
        angle_  = wrap(angle_ + omega_ * dt);                // затем угол
        lastEmf_ = emf(angle_, omega_);                      // противо-ЭДС рамки
    }

    // ── Состояние ─────────────────────────────────────────────────────────────
    double angle()   const { return angle_; }
    double omega()   const { return omega_; }
    double lastEmf() const { return lastEmf_; }

    void reset() {
        angle_   = 0.0;
        omega_   = 0.0;
        lastEmf_ = 0.0;
    }

private:
    // Нормализация угла в (−π, π].
    static double wrap(double a) {
        constexpr double kTwoPi = 2.0 * 3.14159265358979323846;
        a = std::fmod(a, kTwoPi);
        if (a <= -3.14159265358979323846) a += kTwoPi;
        if (a >   3.14159265358979323846) a -= kTwoPi;
        return a;
    }

    int    turns_   = 1;     // N
    double area_    = 1.0;   // A (м²)
    double field_   = 0.0;   // B (Тл)
    double inertia_ = 1.0;   // J (кг·м²)

    double angle_   = 0.0;   // θ
    double omega_   = 0.0;   // ω
    double lastEmf_ = 0.0;   // последняя посчитанная ЭДС
};

} // namespace current_lab::physics
