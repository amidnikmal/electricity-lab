#pragma once
//
// InductionModel — индукция Фарадея на оси: магнит-диполь движется сквозь катушку.
//
// Физическая суть для учебной демки «двигаешь магнит — лампочка вспыхивает; стоит
// магнит — темно»: ток в катушке возникает НЕ от близости магнита, а от ИЗМЕНЕНИЯ
// магнитного потока сквозь её витки. Поэтому неподвижный магнит (v=0) ЭДС не даёт.
//
// Геометрия (всё на одной оси симметрии):
//   - катушка из N витков радиуса R закреплена в координате 0;
//   - магнит — точечный диполь момента m, его осевая координата = axialDistance = d;
//   - магнит движется со скоростью v = dd/dt.
//
// Поток одного витка радиуса R от осевого диполя момента m на расстоянии d по оси:
//
//        Φ₁(d) = (μ₀·m·R²) / (2·(R² + d²)^(3/2))
//
// Полный поток катушки: Φ = N·Φ₁(d) (все витки в одном месте, тонкая катушка).
//
// ЭДС по закону Фарадея с правилом Ленца (знак минус):
//
//        ЭДС = −N·dΦ₁/dd · v
//
// Производную берём АНАЛИТИЧЕСКИ — функция гладкая, численное дифференцирование тут
// не нужно и шумит у d=0:
//
//        dΦ₁/dd = (μ₀·m·R²)/2 · (−3d)·(R²+d²)^(−5/2)
//
// Знаковая картина (это и есть наглядный «двойной всплеск» Ленца):
//   - dΦ₁/dd нечётна по d, обращается в ноль в центре (d=0) → там ЭДС меняет знак;
//   - смена направления движения (v → −v) переворачивает знак ЭДС;
//   - при пролёте магнита сквозь катушку ЭДС даёт два всплеска противоположных знаков
//     (подлёт d<0 и отлёт d>0), а в момент прохождения центра — мгновенный ноль.
//
// Чистый заголовок, без UI/GL; покрыт tests/test_induction.cpp.
// Ядро для демки «Индукция Фарадея» — см.
// docs/RESEARCH_MAGNETISM_MODULES_2026-06-16.md (топ-приоритет 44.8).

#include <cmath>

namespace current_lab::physics {

class InductionModel {
public:
    // Магнитная постоянная (СИ).
    static constexpr double kMu0 = 1.25663706212e-6;

    // Геометрия катушки: число витков N (>0) и радиус витка R (>0).
    void setCoil(int turns, double radius) {
        turns_  = turns;
        radius_ = radius;
    }

    // Дипольный момент магнита m (А·м²). Знак задаёт ориентацию полюсов.
    void setMagnet(double dipoleMoment) {
        dipole_ = dipoleMoment;
    }

    // Поток сквозь ОДИН виток радиуса R от диполя на осевом расстоянии d.
    //   Φ₁(d) = μ₀·m·R² / (2·(R²+d²)^{3/2})
    // Чётная по d (зависит от d²), максимум в центре, монотонно спадает по |d|.
    double fluxPerTurn(double axialDistance) const {
        const double R2 = radius_ * radius_;
        const double s  = R2 + axialDistance * axialDistance;
        return kMu0 * dipole_ * R2 / (2.0 * std::pow(s, 1.5));
    }

    // Полный поток катушки: Φ = N·Φ₁(d). Пропорционален числу витков.
    double totalFlux(double axialDistance) const {
        return turns_ * fluxPerTurn(axialDistance);
    }

    // ЭДС = −N·dΦ₁/dd · v, где
    //   dΦ₁/dd = μ₀·m·R²/2 · (−3d)·(R²+d²)^{−5/2}.
    // Подставляя: ЭДС = N·v · μ₀·m·R²/2 · 3d·(R²+d²)^{−5/2}.
    //   v=0 → ЭДС=0 (неподвижный магнит тока не даёт);
    //   линейна по v; нечётна по d (ноль в центре, смена знака при пролёте).
    double emf(double axialDistance, double velocity) const {
        const double R2 = radius_ * radius_;
        const double s  = R2 + axialDistance * axialDistance;
        const double dFluxPerTurn_dd =
            kMu0 * dipole_ * R2 * 0.5 * (-3.0 * axialDistance) * std::pow(s, -2.5);
        return -turns_ * dFluxPerTurn_dd * velocity;
    }

    // Яркость лампочки для UI: |ЭДС|, нормированная в [0,1] мягким насыщением
    //   b = e / (e + e0),  e = |ЭДС|.
    // e0 — масштаб «половинной яркости»: при e=e0 лампа светит вполнакала (b=0.5).
    // Подобран под типовые параметры демки (N~100, R~0.05 м, m~10 А·м², v~1 м/с):
    // характерная |ЭДС| вблизи катушки тогда порядка десятых долей вольта, поэтому
    // e0=2e-3 В выбран НАМЕРЕННО малым — лампа уверенно вспыхивает при любом
    // заметном движении и гаснет в темноту лишь у самого центра (где dΦ/dd=0) и на
    // больших |d| (где поток уже слаб). Размах яркости при скоростях ~единицы — весь
    // диапазон [0,1].
    // Насыщение гладкое и монотонное: e=0 → b=0, e→∞ → b→1, без жёсткого клампа.
    double lampBrightness(double axialDistance, double velocity) const {
        const double e  = std::abs(emf(axialDistance, velocity));
        const double e0 = 2.0e-3;
        return e / (e + e0);
    }

private:
    int    turns_  = 1;     // N
    double radius_ = 1.0;   // R
    double dipole_ = 0.0;   // m
};

} // namespace current_lab::physics
