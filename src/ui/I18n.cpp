const char* allUiText() {
    static const std::string text = [] {
        std::string out;
        out.reserve(16384);
        for (const auto& [key, value] : dictionary()) {
            out.append(key);
            out.push_back('\n');
            out.append(value);
            out.push_back('\n');
        }
        return out;
    }();
    return text.c_str();
}

void setLanguage(Language language) { g_language = language; }

Language language() { return g_language; }

const char* tr(const char* english) {
    if (g_language == Language::English || !english)
        return english;
    auto it = dictionary().find(english);
    return it != dictionary().end() ? it->second : english;
}

